"""Mesh tables for the ``surface="mesh"`` representation (MeshMetrics).

MeshMetrics meshes masks with VTK: ``vtkDiscreteMarchingCubes`` in 3-D and
``vtkDiscreteFlyingEdges2D`` in 2-D, in a mask padded with one voxel of background. Within each
2x2(x2) block of voxels the result depends only on which voxels are inside, so it is tabulated
here by the block's neighbour code (as in :mod:`exacta.functional._surfel_tables`).

The tables were produced by running those VTK filters (VTK 9.7.1) on every configuration of a
block placed in a zero-padded image and keeping the cells inside the block; exacta's meshing then
reproduces VTK's, triangle for triangle (tests/test_mesh.py). VTK is Copyright Ken Martin, Will
Schroeder, Bill Lorensen, licensed under the BSD 3-Clause License.

Each triangle (segment) is a string of its vertices' coordinates in half-voxel units relative to
the block's first voxel: the digits 0, 1 and 2 stand for 0, 0.5 and 1 voxel, so every value is
exact. Code 1 (only the block's voxel (1, 1, 1) inside) has the single triangle "221212122":
(1, 1, 0.5), (1, 0.5, 1), (0.5, 1, 1), cutting that corner off at the edge midpoints.
"""

