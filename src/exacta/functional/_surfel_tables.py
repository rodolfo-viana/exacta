"""Surface-element tables for the ``surface="surfels"`` representation.

A surface element (surfel) sits at a voxel corner and stands for the part of the surface inside
the 2x2(x2) block of voxels around that corner. The block's neighbour code has one bit per voxel
of the block, set when the voxel is in the mask; it decides the marching-cubes surface inside
the block, and so the element's area (3-D) or length (2-D).

The 3-D normals table is copied from DeepMind's surface-distance
(https://github.com/google-deepmind/surface-distance, surface_distance/lookup_tables.py),
Copyright 2018 Google Inc., licensed under the Apache License, Version 2.0
(http://www.apache.org/licenses/LICENSE-2.0). Each entry lists, for one neighbour code, the
normals of the marching-cubes triangles in the block, scaled so that their length is the
triangle's area on a unit grid. MONAI's copy differs only in the sign of two normals (codes 251
and 253), which does not change any area.
"""

